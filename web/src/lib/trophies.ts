/* Each league's championship trophy, as a one-colour line icon in the page colour (currentColor).
   The drawings come from John's package @johnmorrisdotca/dougu-sports (MIT), not from this site: its generic cups, which
   suggest the trophy rather than reproduce it. Each is imported from its own module so a page takes only these.
   Credited on /terms (Credits.tsx). */
import { TROPHY_BASEBALL } from "@johnmorrisdotca/dougu-sports/trophy/baseball";
import { TROPHY_BASKETBALL } from "@johnmorrisdotca/dougu-sports/trophy/basketball";
import { TROPHY_CANADIAN_BOWL } from "@johnmorrisdotca/dougu-sports/trophy/canadian-bowl";
import { TROPHY_FOOTBALL } from "@johnmorrisdotca/dougu-sports/trophy/football";
import { TROPHY_HOCKEY_CUP } from "@johnmorrisdotca/dougu-sports/trophy/hockey-cup";
import { TROPHY_SOCCER_BALL } from "@johnmorrisdotca/dougu-sports/trophy/soccer-ball";
import { TROPHY_SOCCER_GLOBE } from "@johnmorrisdotca/dougu-sports/trophy/soccer-globe";
import { MEDAL_BRONZE } from "@johnmorrisdotca/dougu-sports/medal/bronze";
import { MEDAL_GOLD } from "@johnmorrisdotca/dougu-sports/medal/gold";
import { MEDAL_SILVER } from "@johnmorrisdotca/dougu-sports/medal/silver";

type Drawing = { svg: (o: { style: "line" | "metal"; size: number }) => string };

/** The package's drawing (line style, or metal for a medal), with its generic title replaced by the name of the trophy the team won.
 *  The width and height are dropped so the page's CSS sizes it (the box is square, 64 by 64). */
const draw = (d: Drawing, name: string, style: "line" | "metal" = "line") =>
  d.svg({ style, size: 64 })
    .replace(/<title>[^<]*<\/title>/, `<title>${name}</title>`)
    .replace(/ width="64" height="64"/, "");

const T: Record<string, string> = {
  // Stanley Cup: the tall banded silver cup.
  nhl: draw(TROPHY_HOCKEY_CUP, "Stanley Cup"),
  // Larry O'Brien Trophy: a basketball over a net.
  nba: draw(TROPHY_BASKETBALL, "Larry O'Brien Trophy"),
  // Commissioner's Trophy: a ring of pennants round a baseball.
  mlb: draw(TROPHY_BASEBALL, "Commissioner's Trophy"),
  // Vince Lombardi Trophy: a football on a stand.
  nfl: draw(TROPHY_FOOTBALL, "Vince Lombardi Trophy"),
  // Grey Cup: the wide two-handled bowl.
  cfl: draw(TROPHY_CANADIAN_BOWL, "Grey Cup"),
  // The World Cup (men's and women's): a globe held up on a column.
  worldcup: draw(TROPHY_SOCCER_GLOBE, "World Cup"),
  wwc: draw(TROPHY_SOCCER_GLOBE, "World Cup"),
  // MLS Cup and other soccer trophies: a soccer ball on a stand.
  mls: draw(TROPHY_SOCCER_BALL, "MLS Cup"),
  soccer: draw(TROPHY_SOCCER_BALL, "Trophy"),
};

/** Trusted, static SVG markup for a league's trophy (generated by the package from fixed drawings, never user input). */
export const trophySvg = (lg: string): string => T[lg] || T.nhl;

const M = {
  1: draw(MEDAL_GOLD, "Gold medal", "metal"),
  2: draw(MEDAL_SILVER, "Silver medal", "metal"),
  3: draw(MEDAL_BRONZE, "Bronze medal", "metal"),
} as const;

/** Trusted, static SVG markup (metal style, so gold, silver and bronze keep their colour) for a first, second or third place medal, or "" for any other place. */
export const medalSvg = (place: number): string => (place === 1 || place === 2 || place === 3 ? M[place] : "");
