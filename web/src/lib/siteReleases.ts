/** Parse 0.47.0 into comparable numbers. */
export function versionParts(v: string): readonly number[] {
  return v.split(".").map((n) => Number(n));
}

/** Negative when a is older than b, positive when newer. */
export function versionCmp(a: string, b: string): number {
  const x = versionParts(a), y = versionParts(b);
  for (let i = 0; i < Math.max(x.length, y.length); i++) {
    const d = (x[i] ?? 0) - (y[i] ?? 0);
    if (d) return d;
  }
  return 0;
}

/** The series a version belongs to: 0.142.6 is in 0.142. */
export function versionSeries(v: string): string {
  return versionParts(v).slice(0, 2).join(".");
}

/** One entry's `<time>` day as a UTC date, from its `date` ("2026-10-16"). */
export function releaseDay(r: SiteRelease): Date {
  return new Date(`${r.date}T00:00:00Z`);
}

/** Newest versions the /releases page sends; the rest are on /releases/older (about 300 KB of HTML is the page budget). */
export const SITE_RELEASE_HEAD = 60;

export function siteReleaseHead(): readonly SiteRelease[] {
  return SITE_RELEASES.slice(0, SITE_RELEASE_HEAD);
}

export function siteReleaseRest(): readonly SiteRelease[] {
  return SITE_RELEASES.slice(SITE_RELEASE_HEAD);
}
