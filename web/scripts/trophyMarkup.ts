import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { TROPHY_BASEBALL } from "@johnmorrisdotca/dougu-sports/trophy/baseball";
import { TROPHY_BASKETBALL } from "@johnmorrisdotca/dougu-sports/trophy/basketball";
import { TROPHY_CANADIAN_BOWL } from "@johnmorrisdotca/dougu-sports/trophy/canadian-bowl";
import { TROPHY_FOOTBALL } from "@johnmorrisdotca/dougu-sports/trophy/football";
import { TROPHY_HOCKEY_CUP } from "@johnmorrisdotca/dougu-sports/trophy/hockey-cup";
import { TROPHY_SOCCER_BALL } from "@johnmorrisdotca/dougu-sports/trophy/soccer-ball";
import { TROPHY_SOCCER_GLOBE } from "@johnmorrisdotca/dougu-sports/trophy/soccer-globe";
import { MEDAL_BRONZE } from "@johnmorrisdotca/dougu-sports/medal/bronze";
import { MEDAL_GOLD } from "@johnmorrisdotca/dougu-sports/medal/gold";
import { MEDAL_SILVER } from "@johnmorrisdotca/dougu-sports/medal/silver";

/**
 * Writes src/lib/trophies.generated.ts and medals.generated.ts: the trophy and medal SVG strings from @johnmorrisdotca/dougu-sports, so the site ships
 * the strings and not the renderer. Run in web/ after any change to the package version or to the list below: pnpm trophies
 * (pnpm test:trophies fails while the file is stale).
 */

type Drawing = { svg: (o: { style: "line" | "metal"; size: number }) => string };

/** The package's drawing with its generic title replaced by the name of the trophy the team won; width and height dropped so the page's CSS sizes it. */
const draw = (d: Drawing, name: string, style: "line" | "metal" = "line") =>
  d.svg({ style, size: 64 })
    .replace(/<title>[^<]*<\/title>/, `<title>${name}</title>`)
    .replace(/ width="64" height="64"/, "");

/** Line-style trophies, keyed by the league (or tournament) the page passes to `trophySvg`. */
const TROPHIES: [string, Drawing, string][] = [
  ["nhl", TROPHY_HOCKEY_CUP, "Stanley Cup"],
  ["nba", TROPHY_BASKETBALL, "Larry O'Brien Trophy"],
  ["mlb", TROPHY_BASEBALL, "Commissioner's Trophy"],
  ["nfl", TROPHY_FOOTBALL, "Vince Lombardi Trophy"],
  ["cfl", TROPHY_CANADIAN_BOWL, "Grey Cup"],
  ["worldcup", TROPHY_SOCCER_GLOBE, "World Cup"],
  ["wwc", TROPHY_SOCCER_GLOBE, "World Cup"],
  ["mls", TROPHY_SOCCER_BALL, "MLS Cup"],
  ["soccer", TROPHY_SOCCER_BALL, "Trophy"],
];

/** Metal-style medals (so gold, silver and bronze keep their colour), keyed by place. */
const MEDALS: [number, Drawing, string][] = [
  [1, MEDAL_GOLD, "Gold medal"],
  [2, MEDAL_SILVER, "Silver medal"],
  [3, MEDAL_BRONZE, "Bronze medal"],
];

const packageVersion = (): string =>
  JSON.parse(readFileSync(fileURLToPath(new URL("../node_modules/@johnmorrisdotca/dougu-sports/package.json", import.meta.url)), "utf8")).version;

const header = () => [
  "// Generated by scripts/trophyMarkup.ts (pnpm trophies) from @johnmorrisdotca/dougu-sports. Do not edit by hand.",
  `// Package version: ${packageVersion()}. Trusted static SVG markup, drawn by the package (MIT); credited on /terms.`,
  "",
];
const entry = (key: string | number, svg: string) => `  ${JSON.stringify(String(key))}: ${JSON.stringify(svg)},`;

/** The whole text of trophies.generated.ts for the installed package version. */
export function trophyMarkup(): string {
  return [
    ...header(),
    "/** Line-style trophies by league key. */",
    "export const TROPHY_MARKUP: Record<string, string> = {",
    ...TROPHIES.map(([k, d, name]) => entry(k, draw(d, name))),
    "};",
    "",
  ].join("\n");
}

/** The whole text of medals.generated.ts: a separate file so the pages that draw no medal never carry them. */
export function medalMarkup(): string {
  return [
    ...header(),
    "/** Metal-style medals by place (1, 2, 3). */",
    "export const MEDAL_MARKUP: Record<string, string> = {",
    ...MEDALS.map(([k, d, name]) => entry(k, draw(d, name, "metal"))),
    "};",
    "",
  ].join("\n");
}

export const GENERATED = fileURLToPath(new URL("../src/lib/trophies.generated.ts", import.meta.url));
export const GENERATED_MEDALS = fileURLToPath(new URL("../src/lib/medals.generated.ts", import.meta.url));

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  writeFileSync(GENERATED, trophyMarkup());
  writeFileSync(GENERATED_MEDALS, medalMarkup());
  console.log(`wrote ${GENERATED} and ${GENERATED_MEDALS}`);
}
