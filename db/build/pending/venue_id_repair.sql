-- DS1 repair, not a build step (it lives in pending/, so build_core.sh never runs it): puts every core.venue back on the venue_id that
-- ingest.row_id_map remembers for its key, and repoints everything that holds a venue id.
-- Why: on 2026-10-19 a rerun of 176 and 198 deleted and re-added 35 venues, which gave them new ids while production keeps the old ones
-- (db/checks/093_row_id_drift.sql returned 35 rows). 176 and 198 now give the remembered id back, so this is a one-off repair.
-- Run with: bash scripts/mac/ds1-apply.sh db/build/pending/venue_id_repair.sql [--dry-run]   (DS1 only; one transaction, no begin or commit here).
-- Rerunnable: with nothing to repair it changes nothing. Needs the role to be a superuser (the postgres login ds1-apply uses): the foreign keys
-- are switched off for this transaction only (session_replication_role = replica) so every table can move to the old id, and every foreign key
-- is checked again below before the transaction ends (an orphan raises and rolls everything back). core.venue.venue_id, an identity
-- column that refuses updates, is switched to generated by default for the transaction and back to always at the end.
--
-- What it touches, found in the catalog and not from a list: every foreign key that points at core.venue (core.venue_name, venue_feature,
-- franchise_venue, franchise_home_venue, game_venue, venue_game_season, venue_final_game, game.venue_id, team_season.home_venue_id,
-- soccer_match.venue_id ...), plus the two tables that hold a venue id with no foreign key (legacy_game_venue.filled and home_prelim).
-- It stops, changing nothing, if another table in schema core or legacy_game_venue has a column named venue_id or ending in _venue_id that is not
-- on that list, or if an old id is held by a venue that is not itself being renumbered. The brand_venue_* tables and core.venue_pitch are keyed
-- by the Wikidata item, not the id, and need nothing. No materialized view holds a venue id.
-- Two passes (to a negative id, then to the old one) so ids that swap places never meet.
-- Expected on DS1 on 2026-10-19: 35 venues renumbered; the row counts per table are printed (notice lines), core.venue stays 796 rows,
-- core.venue_name 849; afterwards db/checks/093_row_id_drift.sql returns 0 rows.

create temp table venue_swap as
select m.natural_key, c.id as new_id, m.row_id as old_id
from ingest.row_id_map m
join ingest.row_id_current c on c.tbl = m.tbl and c.natural_key = m.natural_key
where m.tbl = 'core.venue' and c.id <> m.row_id;

create temp table venue_holder (sch text, tbl text, col text, is_fk boolean);
insert into venue_holder
select n.nspname, c.relname, a.attname, true
from pg_constraint k
join pg_class c on c.oid = k.conrelid
join pg_namespace n on n.oid = c.relnamespace
join pg_attribute a on a.attrelid = k.conrelid and a.attnum = k.conkey[1]
where k.contype = 'f' and k.confrelid = 'core.venue'::regclass and array_length(k.conkey, 1) = 1;
insert into venue_holder
select v.sch, v.tbl, 'venue_id', false
from (values ('legacy_game_venue', 'filled'), ('legacy_game_venue', 'home_prelim')) v(sch, tbl)
where to_regclass(v.sch || '.' || v.tbl) is not null
  and not exists (select 1 from venue_holder h where h.sch = v.sch and h.tbl = v.tbl and h.col = 'venue_id');

do $$
declare
  h record;
  was_always boolean;
  n bigint;
  swapped integer;
  bad text;
begin
  select count(*) into swapped from venue_swap;
  if swapped = 0 then
    raise notice 'venue ids: nothing to repair (every core.venue id is the remembered one)';
    return;
  end if;

  if not exists (select 1 from pg_roles where rolname = current_user and rolsuper) then
    raise exception 'venue ids: this repair switches foreign keys off for its transaction and needs a superuser login (ds1-apply uses postgres)';
  end if;
  if exists (select 1 from venue_swap group by old_id having count(*) > 1) then
    raise exception 'venue ids: two venues are remembered under the same old id';
  end if;
  select string_agg(q.old_id::text || ' (now ' || v.source_key || ')', ', ') into bad
    from venue_swap q join core.venue v on v.venue_id = q.old_id
   where q.old_id not in (select new_id from venue_swap);
  if bad is not null then
    raise exception 'venue ids: an old id is held by a venue that is not being renumbered: %', bad;
  end if;
  -- a column that holds a venue id and is not handled
  select string_agg(c.table_schema || '.' || c.table_name || '.' || c.column_name, ', ') into bad
    from information_schema.columns c
    join information_schema.tables t on t.table_schema = c.table_schema and t.table_name = c.table_name and t.table_type = 'BASE TABLE'
   where c.table_schema in ('core', 'legacy_game_venue')
     and (c.column_name = 'venue_id' or c.column_name like '%\_venue\_id')
     and not (c.table_schema = 'core' and c.table_name = 'venue')
     and not exists (select 1 from venue_holder vh where vh.sch = c.table_schema and vh.tbl = c.table_name and vh.col = c.column_name);
  if bad is not null then
    raise exception 'venue ids: columns that hold a venue id and are not handled by this file: %', bad;
  end if;

  perform set_config('session_replication_role', 'replica', true);
  -- core.venue.venue_id is GENERATED ALWAYS, which refuses an update: allow it for this transaction (the sequence is not touched) and set it back below
  select a.attidentity = 'a' into was_always from pg_attribute a where a.attrelid = 'core.venue'::regclass and a.attname = 'venue_id';
  if was_always then alter table core.venue alter column venue_id set generated by default; end if;

  -- pass 1: to the negative of the id they hold now
  update core.venue v set venue_id = -s.new_id from venue_swap s where v.venue_id = s.new_id;
  get diagnostics n = row_count;
  raise notice 'core.venue pass 1: % rows', n;
  for h in select * from venue_holder order by sch, tbl, col loop
    execute format('update %I.%I t set %I = -s.new_id from venue_swap s where t.%I = s.new_id', h.sch, h.tbl, h.col, h.col);
    get diagnostics n = row_count;
    raise notice '%.%.% pass 1: % rows', h.sch, h.tbl, h.col, n;
  end loop;

  -- pass 2: to the remembered id
  update core.venue v set venue_id = s.old_id from venue_swap s where v.venue_id = -s.new_id;
  get diagnostics n = row_count;
  if n <> swapped then raise exception 'venue ids: renumbered % venues, expected %', n, swapped; end if;
  for h in select * from venue_holder order by sch, tbl, col loop
    execute format('update %I.%I t set %I = s.old_id from venue_swap s where t.%I = -s.new_id', h.sch, h.tbl, h.col, h.col);
    get diagnostics n = row_count;
    raise notice '%.%.%: % rows moved to the remembered id', h.sch, h.tbl, h.col, n;
  end loop;

  if was_always then alter table core.venue alter column venue_id set generated always; end if;
  perform set_config('session_replication_role', 'origin', true);

  -- the foreign keys were off: check every one of them for the values it holds
  for h in select * from venue_holder where is_fk order by sch, tbl, col loop
    execute format('select count(*) from %I.%I t where t.%I is not null and not exists (select 1 from core.venue v where v.venue_id = t.%I)',
                   h.sch, h.tbl, h.col, h.col) into n;
    if n > 0 then
      raise exception 'venue ids: % rows of %.%.% point at no venue', n, h.sch, h.tbl, h.col;
    end if;
  end loop;
  if exists (select 1 from core.venue where venue_id < 0) then
    raise exception 'venue ids: a venue was left on a negative id';
  end if;
  raise notice 'venue ids: % venues back on the remembered id', swapped;
end $$;

select 'venues renumbered by this run' as what, (select count(*) from venue_swap) as n
union all select 'venues still off the remembered id (check 093 says 0)',
  (select count(*) from ingest.row_id_map m join ingest.row_id_current c on c.tbl = m.tbl and c.natural_key = m.natural_key
    where m.tbl = 'core.venue' and c.id <> m.row_id)
union all select 'core.venue rows', count(*) from core.venue
union all select 'core.venue_name rows', count(*) from core.venue_name;
